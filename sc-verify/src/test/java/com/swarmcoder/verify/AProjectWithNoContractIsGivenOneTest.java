package com.swarmcoder.verify;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * <b>A project that has no verification contract is given one, and nothing a worker can write
 * is ever read as the contract</b> (section 107).
 *
 * <p>A live build made a project from an empty folder and ran to its end with every candidate
 * unverified: nothing wrote {@code .swarmcoder/verify.yaml}. Here the contract is made from
 * the names of build files alone - the ones in the project's folder, or the ones a plan names
 * for a folder that is still empty - and is written into the project's own folder, the only
 * place the contract is read from.
 */
class AProjectWithNoContractIsGivenOneTest {

    @TempDir
    Path project;
    @TempDir
    Path workersTree;

    @Test
    void aPlanThatNamesMavenModulesGivesAnEmptyFolderTheMavenContract() throws IOException {
        ContractInUse contract = GeneratedContract.provide(project,
            List.of("pom.xml", "core/pom.xml", "app/pom.xml", "core/src/main/java"));

        assertThat(contract.present()).isTrue();
        assertThat(contract.origin()).isEqualTo(ContractInUse.GENERATED);
        assertThat(contract.basis()).contains("the plan names").contains("core/pom.xml");
        VerifySpec spec = contract.spec();
        assertThat(spec.toolchain()).isEqualTo("maven");
        assertThat(spec.compile()).containsExactly("mvn -o -B -q test-compile");
        assertThat(spec.acceptance()).singleElement().satisfies(command -> {
            assertThat(command).as("offline, batch, quiet").startsWith("mvn -o -B -q test ");
            assertThat(command).as("selected by path; the dotted form selects nothing")
                .contains("-Dtest=swarm/accept/**").doesNotContain("swarm.accept");
            assertThat(command).contains("-Dsurefire.failIfNoSpecifiedTests=false");
            assertThat(command).as("from the repository root, so the reactor orders itself")
                .doesNotContain("-pl ").doesNotContain("cd ");
        });
        assertThat(spec.existing()).containsExactly("mvn -o -B -q test");
        assertThat(spec.acceptanceReportDirs())
            .containsExactly("{module}/target/surefire-reports", "{module}/target/failsafe-reports");

        assertThat(project.resolve(VerifySpecLoader.SPEC_PATH)).isRegularFile();
        assertThat(VerifySpecLoader.loadTrusted(project, workersTree)).contains(spec);
        assertThat(contract.describe()).hasSize(2);
        assertThat(String.join(" ", contract.describe()))
            .contains("generated by SwarmCoder").contains("mvn -o -B -q test-compile")
            .contains("-Dtest=swarm/accept/**");
    }

    @Test
    void theBuildFilesInTheFolderDecideBeforeThePlanDoes() throws IOException {
        Files.writeString(project.resolve("build.gradle"), "plugins { id 'java' }\n");

        ContractInUse contract = GeneratedContract.provide(project, List.of("pom.xml"));

        assertThat(contract.spec().toolchain()).isEqualTo("gradle");
        assertThat(contract.basis()).contains("the project's folder");
        assertThat(contract.spec().compile()).allMatch(command -> command.contains("--offline"));
    }

    @Test
    void aContractThatIsThereIsNeverReplacedWhetherItReadsOrNot() throws IOException {
        Path file = project.resolve(VerifySpecLoader.SPEC_PATH);
        Files.createDirectories(file.getParent());
        String byHand = "toolchain: maven\ncompile:\n  - \"mvn -o -q compile\"\n";
        Files.writeString(file, byHand);

        ContractInUse kept = GeneratedContract.provide(project, List.of("pom.xml"));

        assertThat(kept.origin()).isEqualTo(ContractInUse.PROJECT_FILE);
        assertThat(kept.spec().compile()).containsExactly("mvn -o -q compile");
        assertThat(Files.readString(file)).isEqualTo(byHand);

        String broken = "toolchain: maven\ncompile: [\"unclosed\n";
        Files.writeString(file, broken);

        ContractInUse unreadable = GeneratedContract.provide(project, List.of("pom.xml"));

        assertThat(unreadable.present()).isFalse();
        assertThat(unreadable.thereAndUnreadable()).isTrue();
        assertThat(Files.readString(file)).as("a mistake in it is the person's to correct")
            .isEqualTo(broken);
    }

    @Test
    void noContractPassesOnlyWhenNothingIsOwedAndAnUnreadableOneNeverPasses() throws IOException {
        ContractInUse none = GeneratedContract.provide(project,
            List.of("src/main/java/A.java", "package.json"));

        assertThat(none.present()).as("no build system this class has commands for").isFalse();
        assertThat(project.resolve(VerifySpecLoader.SPEC_PATH)).doesNotExist();
        assertThat(none.refusal(0, 0, "this run")).as("the allowance of milestone 1").isNull();
        assertThat(none.refusal(1, 0, "this run"))
            .contains("NOTHING CAN BE VERIFIED").contains("There is no verification contract")
            .contains(VerifySpecLoader.SPEC_PATH).contains("build-contract dialog");
        assertThat(none.refusal(0, 1, "this run")).isNotNull();

        Path file = project.resolve(VerifySpecLoader.SPEC_PATH);
        Files.createDirectories(file.getParent());
        Files.writeString(file, "compile: [\"unclosed\n");
        ContractInUse unreadable = VerifySpecLoader.inUse(project, workersTree);

        assertThat(unreadable.refusal(0, 0, "this run"))
            .as("nothing is owed, and it still does not pass")
            .contains("is there and cannot be read");
        assertThat(unreadable.describe()).singleElement().asString().contains("NONE");
    }

    @Test
    void aCopyInAWorkersTreeIsNeverReadAsTheContract() throws IOException {
        Path workers = workersTree.resolve(VerifySpecLoader.SPEC_PATH);
        Files.createDirectories(workers.getParent());
        Files.writeString(workers, "toolchain: maven\ncompile:\n  - \"true\"\n");

        assertThat(VerifySpecLoader.loadTrusted(project, workersTree))
            .as("the project has none: a worker's own file does not become it").isEmpty();
        assertThat(VerifySpecLoader.inUse(project, workersTree).present()).isFalse();
        assertThat(VerifySpecLoader.inUse(project, workersTree).refusal(1, 0, "a candidate"))
            .contains("a copy there is never used");

        Path own = project.resolve(VerifySpecLoader.SPEC_PATH);
        Files.createDirectories(own.getParent());
        Files.writeString(own, "compile: [\"unclosed\n");
        assertThat(VerifySpecLoader.loadTrusted(project, workersTree))
            .as("the project's own does not parse: the worker's copy is still not used")
            .isEmpty();

        Files.writeString(own, "toolchain: maven\ncompile:\n  - \"mvn -o -q compile\"\n");
        assertThat(VerifySpecLoader.loadTrusted(project, workersTree).orElseThrow().compile())
            .containsExactly("mvn -o -q compile");

        // What the product generates goes to the project's folder, whatever a tree holds.
        Files.delete(own);
        Files.writeString(workersTree.resolve("pom.xml"), "<project/>");
        ContractInUse generated = GeneratedContract.provide(project,
            GeneratedContract.buildFilesIn(workersTree));
        assertThat(generated.origin()).isEqualTo(ContractInUse.GENERATED);
        assertThat(generated.spec().compile()).containsExactly("mvn -o -B -q test-compile");
        assertThat(Files.readString(workers)).as("the worker's copy is neither read nor written")
            .contains("\"true\"");
    }

    @Test
    void reportsAreWalkedInEveryModuleTheTreeHoldsWhenTheStageRuns() throws IOException {
        for (String pom : List.of("pom.xml", "core/pom.xml", "app/web/pom.xml",
                "core/target/classes/META-INF/maven/x/pom.xml")) {
            Files.createDirectories(workersTree.resolve(pom).getParent());
            Files.writeString(workersTree.resolve(pom), "<project/>");
        }

        List<String> walked = GeneratedContract.reportDirsOn(
            new LocalProcessExecTarget(workersTree),
            List.of("{module}/target/surefire-reports", "elsewhere/reports"));

        assertThat(walked).containsExactly("target/surefire-reports",
            "app/web/target/surefire-reports", "core/target/surefire-reports",
            "elsewhere/reports");
        assertThat(GeneratedContract.reportDirsOn(new LocalProcessExecTarget(workersTree),
            List.of("target/surefire-reports"))).containsExactly("target/surefire-reports");
    }

    @Test
    void acceptanceTestsOfAPlannedReactorGoInAModuleThatCompilesNotInItsAggregator() {
        BuildLayout.Layout reactor = GeneratedContract.plannedLayout(
            List.of("pom.xml", "core/pom.xml", "app/pom.xml"), Map.of("app", List.of("core")));

        assertThat(reactor.compilingModules()).as("the root only orders its modules")
            .containsExactly("app", "core");
        AcceptanceTestLocation.Location place = AcceptanceTestLocation.resolve(reactor);
        assertThat(place.writeDir()).isEqualTo("app/src/test/java/swarm/accept");
        assertThat(place.seesEveryModule()).isTrue();

        BuildLayout.Layout single = GeneratedContract.plannedLayout(List.of("pom.xml"), Map.of());
        assertThat(AcceptanceTestLocation.resolve(single).writeDir())
            .isEqualTo("src/test/java/swarm/accept");
        assertThat(GeneratedContract.plannedLayout(List.of("src/Main.java"), Map.of())).isNull();
    }

    @Test
    void aTreeWithNoBuildFileYetIsRedWithoutRunningAnything() {
        VerifySpec generated = GeneratedContract.propose(List.of("pom.xml"), "test")
            .orElseThrow().spec();
        FakeExecTarget empty = new FakeExecTarget();

        RedChecker.RedCheckResult red = new RedChecker().check(empty, generated);

        assertThat(red.red()).isTrue();
        assertThat(red.note()).contains("no maven build file yet");
        assertThat(empty.executedCommands).as("no command is run on a tree nothing can build")
            .isEmpty();
        assertThat(RedChecker.noBuildYet(new FakeExecTarget().file("pom.xml", "<project/>"),
            generated)).isFalse();
        VerifySpec byHand = new VerifySpec("maven", List.of("mvn compile"), List.of("mvn test"),
            List.of(), List.of(), List.of(), null, 60, null);
        assertThat(RedChecker.noBuildYet(empty, byHand))
            .as("a contract a person wrote is run as it always was").isFalse();
    }
}
