package com.swarmcoder.verify;

import java.util.ArrayList;
import java.util.List;

/**
 * The verification contract a run is held to, where it came from, and the one rule for a place
 * that has none (section 107).
 *
 * <p>There are three states and they are different facts. A contract that reads is used. A
 * contract file that is there and does not read is never "no contract": every reader fails on
 * it, whatever is owed. No contract file at all passes only when nothing is owed - no check is
 * claimed and no acceptance test is due - which is the allowance of milestone 1 and nothing
 * more. {@link #refusal} is that rule, in one place, for the swarm engine's candidate
 * verification, the compile check between waves, the delivery onto the project's branch and
 * the start of a run.
 *
 * @param spec       the contract, or null when none reads
 * @param origin     {@link #PROJECT_FILE} or {@link #GENERATED}; null when there is none
 * @param basis      for a generated contract, what it was generated from; null otherwise
 * @param unreadable why the file that is there cannot be read; null when it reads or is absent
 * @param looked     where it was looked for and what was found there
 */
public record ContractInUse(VerifySpec spec, String origin, String basis, String unreadable,
                            String looked) {

    /** Written by a person, or saved from the Console's build-contract dialog. */
    public static final String PROJECT_FILE = "project file";

    /** Written by SwarmCoder for a recognised build system; no model had a part in it. */
    public static final String GENERATED = "generated by SwarmCoder";

    public boolean present() {
        return spec != null;
    }

    /** True when a contract file is there and cannot be read. */
    public boolean thereAndUnreadable() {
        return unreadable != null;
    }

    /**
     * Null when work may go on under this contract; otherwise what is missing and how to supply
     * it, for the question the run stops with.
     *
     * @param checksOwed how many checks are claimed by the work about to be verified
     * @param testsDue   how many acceptance test files are due on its tree
     * @param what       the work, as the sentence names it: "this run", "the candidate of 'x'"
     */
    public String refusal(int checksOwed, int testsDue, String what) {
        return refusal(checksOwed, testsDue, what, "then answer this question. Nothing is "
            + "lost: the run goes on from this stage.");
    }

    /**
     * @param thenWhat how the sentence about supplying the contract ends: what the person does
     *                 once the contract is there
     */
    public String refusal(int checksOwed, int testsDue, String what, String thenWhat) {
        if (present()) {
            return null;
        }
        if (!thereAndUnreadable() && checksOwed <= 0 && testsDue <= 0) {
            return null; // no contract anywhere and nothing owed: the milestone 1 allowance
        }
        StringBuilder why = new StringBuilder("NOTHING CAN BE VERIFIED. ");
        if (thereAndUnreadable()) {
            why.append("The verification contract (").append(VerifySpecLoader.SPEC_PATH)
                .append(") is there and cannot be read: ").append(unreadable).append(". ");
        } else {
            why.append("There is no verification contract: ").append(looked).append(". ");
        }
        why.append("The contract holds the commands that build the project and run its tests; "
            + "without it nothing is compiled and no test is run, so ").append(what)
            .append(" would be accepted on nothing. ").append(checksOwed)
            .append(" check(s) are claimed and ").append(testsDue)
            .append(" acceptance test file(s) are due.\n\n");
        if (thereAndUnreadable()) {
            why.append("Correct the file in the project's own folder, ").append(thenWhat);
        } else {
            why.append("SwarmCoder writes the contract itself when it can tell how the project "
                + "is built: from a Maven or Gradle build file in the project's folder, or from "
                + "the build files the plan names. Neither was found. Either save one from the "
                + "Console's build-contract dialog (it proposes the commands once a build file "
                + "is in the folder), or write ").append(VerifySpecLoader.SPEC_PATH)
                .append(" in the project's own folder by hand with the keys toolchain, compile, "
                    + "acceptance and existing; ").append(thenWhat);
        }
        return why.toString();
    }

    /**
     * The contract in one or two lines, for the run's record: where it came from and which
     * commands it holds.
     */
    public List<String> describe() {
        List<String> lines = new ArrayList<>();
        if (!present()) {
            lines.add("Verification contract: NONE"
                + (thereAndUnreadable() ? " - the file is there and cannot be read: " + unreadable
                    : " - " + looked) + ".");
            return lines;
        }
        lines.add("Verification contract: " + origin
            + (basis == null || basis.isBlank() ? "" : ", " + basis)
            + " (" + VerifySpecLoader.SPEC_PATH + " in the project's own folder; toolchain "
            + spec.toolchain() + ").");
        lines.add("Its commands - compile: " + stage(spec.compile()) + " | acceptance: "
            + stage(spec.acceptance()) + " | existing: " + stage(spec.existing()) + ".");
        return lines;
    }

    private static String stage(List<String> commands) {
        return commands == null || commands.isEmpty() ? "none" : String.join(" ; ", commands);
    }
}
